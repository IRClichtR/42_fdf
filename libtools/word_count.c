#include "libtools.h"

int	word_count(char *str)
{
	int	i;
	int	count;

	i = 0;
	count = 1;
	while (str[i])
	{
		if (str[i] == ' ' 
		&& (str[i + 1] != '\0' || str[i + 1] != 10 || str[i + 1] != ' '))
			count += 1;
		i++;
	}
	return (count);
}
